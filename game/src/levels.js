/** Parse one level's rows into the structures the engine uses. */
export function parseLevel(levelIndex) {
  const level = LEVELS[levelIndex];
  const grid = [];
  const petals = [];
  const lanterns = [];
  let playerStart = null;
  let exit = null;
  for (let y = 0; y < ROWS; y += 1) {
    const raw = level.rows[y] || '';
    const row = [];
    for (let x = 0; x < COLS; x += 1) {
      let ch = raw[x] || ',';
      if (ch === 'P') {
        playerStart = { x: x * TILE + TILE / 2, y: y * TILE + TILE / 2 };
        ch = ',';
      } else if (ch === 'E') {
        exit = { x: x * TILE + TILE / 2, y: y * TILE + TILE / 2 };
        ch = ',';
      } else if (ch === '*') {
        petals.push({ x: x * TILE + TILE / 2, y: y * TILE + TILE / 2, taken: false, bob: (x * 7 + y * 13) % 10 });
        ch = ',';
      } else if (ch === 'G') {
        ch = ',';
      } else if (ch === 'L') {
        lanterns.push({ x: x * TILE + TILE / 2, y: y * TILE + TILE / 2, flicker: (x * 31 + y * 17) % 100 });
      }
      row.push(ch);
    }
    grid.push(row);
  }
  return { level, grid, petals, lanterns, playerStart, exit };
}

/** Tile character at pixel coordinates (out of bounds counts as hedge). */
export function tileAt(grid, px, py) {
  const tx = Math.floor(px / TILE);
  const ty = Math.floor(py / TILE);
  if (tx < 0 || ty < 0 || tx >= COLS || ty >= ROWS) return '#';
  return grid[ty][tx];
}

/** Is this tile walkable for something with the given radius? */
export function walkableAt(grid, px, py, radius) {
  const corners = [
    [px - radius, py - radius],
    [px + radius, py - radius],
    [px - radius, py + radius],
    [px + radius, py + radius],
  ];
  for (const [cx, cy] of corners) {
    if (SOLID.has(tileAt(grid, cx, cy))) return false;
  }
  return true;
}
